ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;

UPDATE users
SET role = CASE role
    WHEN 'ADMIN' THEN 'PRODUCER'
    WHEN 'PROJECT_MANAGER' THEN 'PRODUCER'
    WHEN 'DEVELOPER' THEN 'TEAM_MEMBER'
    ELSE role
END;

ALTER TABLE users
    ADD CONSTRAINT users_role_check
        CHECK (role IN ('PRODUCER', 'CONTENT_MANAGER', 'TEAM_MEMBER'));
